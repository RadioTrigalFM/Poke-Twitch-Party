/* =========================================================
   CATEGORÍAS — MODO VOLTORB EXPLOSIVO
   -----------------------------------------------------------
   Cada categoría tiene un nombre y una lista de "items" válidos.
   Durante una ronda, los jugadores van nombrando elementos de la
   categoría activa (sin poder repetir ninguno ya dicho por otro
   jugador en esa misma ronda) hasta que se agotan todos.
   ========================================================= */
// Devuelve el nombre "de pantalla" de un item de categoría: los items
// normales son directamente un string, pero algunos (p.ej. los Pokémon
// Paradoja de la categoría "Pokémon de novena generación") son un objeto
// { name, aliases } para poder aceptar tanto el nombre en español como en
// inglés como respuesta válida. veItemName() siempre da el nombre
// "canónico" que se muestra en el cartel/progreso/chip.
export function veItemName(it) {
  return typeof it === 'string' ? it : it.name;
}

// Devuelve TODAS las formas válidas de nombrar un item (el nombre
// canónico + sus alias, si los tiene), para comprobar si lo que ha
// escrito el chat coincide con cualquiera de ellas.
export function veItemAliases(it) {
  if (typeof it === 'string') return [it];
  return [it.name, ...(it.aliases || [])];
}

// Devuelve todas las formas válidas de nombrar un item PARA COMPROBAR LA
// RESPUESTA DEL CHAT: además de veItemAliases(it), añade:
// - una variante sin la palabra "de" para los Pokémon de forma regional o
//   racial ("X de Alola", "X de Hisui", "X de Galar", "X de Paldea", etc.),
//   de forma que también se acepte la forma abreviada más habitual en el
//   chat (p.ej. "ninetales alola" o "tauros paldea" son tan válidos como
//   "ninetales de alola" o "tauros de paldea").
// - para las bayas ("baya X"), una variante sin el prefijo "baya ", para
//   que "caquic" cuente igual que "baya caquic".
// - para las Poké Balls ("X ball"), una variante sin el sufijo " ball",
//   para que "acopio" cuente igual que "acopio ball".
export function veItemMatchVariants(it) {
  const aliases = veItemAliases(it);
  const extra = [];
  aliases.forEach(a => {
    if (/\bde\b/i.test(a)) extra.push(a.replace(/\bde\b/gi, ' '));
    if (/^baya\s+/i.test(a)) extra.push(a.replace(/^baya\s+/i, ''));
    if (/\s+ball$/i.test(a)) extra.push(a.replace(/\s+ball$/i, ''));
  });
  return [...aliases, ...extra];
}

