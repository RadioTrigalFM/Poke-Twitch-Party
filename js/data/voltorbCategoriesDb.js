// Elige una categoría al azar, evitando (si es posible) repetir el nombre
// de la última categoría usada, para que dos rondas seguidas no salgan
// exactamente igual.
export function pickVoltorbCategory(excludeName) {
  const pool = VOLTORB_CATEGORIES.filter(c => c.name !== excludeName);
  const list = pool.length ? pool : VOLTORB_CATEGORIES;
  return list[Math.floor(Math.random() * list.length)];
}
